from datetime import datetime, timezone
from fastapi import APIRouter, HTTPException
from backend.app.repositories.ecosystem_repository import ecosystem_repo
from backend.app.services.scenario_service import scenario_service
from backend.app.services.health_service import health_service
from backend.app.schemas.models import (
    ScenarioRequest,
    ScenarioResponse,
    ExecutiveReportResponse,
)

router = APIRouter(tags=["Restoration Time Machine & Reporting"])

_scenario_cache: dict[str, ScenarioResponse] = {}

@router.post("/areas/{area_id}/scenarios", response_model=ScenarioResponse)
def calculate_scenario(area_id: str, request: ScenarioRequest):
    """Run deterministic multi-horizon scenario projection (2025-2045) comparing baseline with restoration."""
    result = scenario_service.calculate_scenario(area_id, request)
    if not result:
        raise HTTPException(status_code=404, detail=f"Scenario calculation failed for area '{area_id}'.")
    
    # Cache under a generated key for retrieval
    cache_id = f"{area_id}_scen_{len(_scenario_cache) + 1}"
    _scenario_cache[cache_id] = result
    return result

@router.get("/areas/{area_id}/scenarios/{scenario_id}", response_model=ScenarioResponse)
def get_scenario_by_id(area_id: str, scenario_id: str):
    """Retrieve a previously calculated scenario by scenario_id."""
    if scenario_id in _scenario_cache:
        return _scenario_cache[scenario_id]
    # Default to generating default baseline scenario if ID not found
    default_req = ScenarioRequest(
        scenario_name="Standard Ecosystem Recovery Plan",
        action_ids=["wg_act_01", "wg_act_02"] if "forest" in area_id else ["sb_act_01", "sb_act_02"]
    )
    result = scenario_service.calculate_scenario(area_id, default_req)
    if not result:
        raise HTTPException(status_code=404, detail=f"Scenario '{scenario_id}' not found.")
    return result

@router.post("/areas/{area_id}/report", response_model=ExecutiveReportResponse)
def generate_executive_report(area_id: str):
    """Generate an executive ecological report synthesizing health metrics, vulnerabilities, and prioritized action plan."""
    area = ecosystem_repo.get_area(area_id)
    if not area:
        raise HTTPException(status_code=404, detail=f"Area '{area_id}' not found.")
    
    summary = health_service.get_area_health_summary(area_id)
    if not summary:
        raise HTTPException(status_code=404, detail="Health summary unavailable.")

    now_iso = datetime.now(timezone.utc).isoformat()

    indicator_lines = "\n".join([f"- **{i.name}**: {i.value}/100 ({i.category.title()}) - *{i.interpretation}*" for i in summary.indicators])

    md = f"""# PRITHVI LABS - ECOSYSTEM RESTORATION REPORT
**Target Ecosystem**: {area.name} ({area.ecosystem_type})  
**Evaluation Date**: {now_iso[:10]}  
**Platform**: Ecosystem Rewind (Phase 1 & 2 Intelligence Engine)  

---

## 1. Executive Summary
The **{area.name}** encompasses approximately **{area.area_size:,.0f} {area.area_size_unit}** within the {area.climate_zone}. 
Our multi-dimensional ecological assessment indicates an overall health score of **{summary.overall_health_score}/100** ({summary.health_status}).

### Key Ecological Indicators:
{indicator_lines}

---

## 2. Structural Vulnerabilities
{area.vulnerability_notes}

---

## 3. Recommended Restoration Strategy
Restoration efforts must target primary ecological bottlenecks:
1. Re-establish habitat corridor continuity to reconnect fragmented populations.
2. Enhance native pollinator floral resources and buffer against edge contamination.
3. Protect keystone species that provide outsized seed dispersal and trophic moderation services.

---

*Report generated by PRITHVI LABS Ecosystem Rewind Platform. Data mode: {area.data_mode}.*
"""

    return ExecutiveReportResponse(
        area_id=area_id,
        area_name=area.name,
        generated_at=now_iso,
        markdown_content=md,
        key_metrics_summary={
            "overall_health": summary.overall_health_score,
            "health_status": summary.health_status,
            "total_indicators": len(summary.indicators)
        }
    )
